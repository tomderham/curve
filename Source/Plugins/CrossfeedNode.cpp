CrossfeedNode::CrossfeedNode()
    : AudioPluginInstance (BusesProperties()
                            .withInput  ("Input",  juce::AudioChannelSet::stereo(), true)
                            .withOutput ("Output", juce::AudioChannelSet::stereo(), true))
{
    // Load direct impulse response
    juce::AudioBuffer<float> dirBuf (1, CrossfeedData::numSamples);
    dirBuf.copyFrom (0, 0, CrossfeedData::directIR, CrossfeedData::numSamples);
    directConvolution.loadImpulseResponse (std::move (dirBuf), CrossfeedData::sampleRate,
                                           juce::dsp::Convolution::Stereo::no,
                                           juce::dsp::Convolution::Trim::no,
                                           juce::dsp::Convolution::Normalise::no);

    // Load crossfeed impulse response
    juce::AudioBuffer<float> crossBuf (1, CrossfeedData::numSamples);
    crossBuf.copyFrom (0, 0, CrossfeedData::crossIR, CrossfeedData::numSamples);
    crossConvolution.loadImpulseResponse (std::move (crossBuf), CrossfeedData::sampleRate,
                                          juce::dsp::Convolution::Stereo::no,
                                          juce::dsp::Convolution::Trim::no,
                                          juce::dsp::Convolution::Normalise::no);
}

